// Read MAPS_API_KEY from local.properties and inject into the manifest.
// Falls back to an empty string so the demo flavor builds without a key.
val mapsApiKey: String = try {
    val localProps = Properties()
    localProps.load(rootProject.file("local.properties").inputStream())
    localProps.getProperty("MAPS_API_KEY", "")
} catch (_: java.io.FileNotFoundException) {
    ""
}

android.apply {
    defaultConfig.manifestPlaceholders["mapsApiKey"] = mapsApiKey
}

